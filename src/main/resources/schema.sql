CREATE TABLE IF NOT EXISTS fornecedor (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL, cnpj VARCHAR(18) NOT NULL UNIQUE,
 email VARCHAR(120) NOT NULL, telefone VARCHAR(25) NOT NULL
);
CREATE TABLE IF NOT EXISTS produto (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL, descricao VARCHAR(500) NOT NULL,
 categoria VARCHAR(50) NOT NULL, preco DECIMAL(12,2) NOT NULL CHECK (preco >= 0),
 quantidade INT NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
 minimo INT NOT NULL CHECK (minimo >= 0), fornecedor_id BIGINT NOT NULL REFERENCES fornecedor(id)
);
CREATE TABLE IF NOT EXISTS movimentacao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 produto_id BIGINT NOT NULL REFERENCES produto(id), tipo VARCHAR(7) NOT NULL CHECK (tipo IN ('ENTRADA','SAIDA')),
 quantidade INT NOT NULL CHECK (quantidade > 0), observacao VARCHAR(250) NOT NULL,
 usuario VARCHAR(100) NOT NULL, data_hora TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
